"use strict";

const fs = require("fs");
const path = require("path");
const vm = require("vm");

const UI = path.join(__dirname, "..", "web", "js", "ui.js");
const API = path.join(__dirname, "..", "web", "js", "api.js");

// ------------------------------------------------------------------
// ดึงเฉพาะฟังก์ชันที่ต้องทดสอบออกมาจากไฟล์จริง
//
// ทำไมไม่ require ทั้งไฟล์: ui.js เขียนสำหรับเบราว์เซอร์ อ้าง document/window
// ตั้งแต่โหลด และไม่มี module.exports การดึงเฉพาะฟังก์ชันทำให้ทดสอบ
// **โค้ดตัวจริงที่เว็บใช้** ได้โดยไม่ต้องจำลองทั้ง DOM
// ------------------------------------------------------------------
function grab(source, name) {
  const start = source.indexOf(`function ${name}(`);
  if (start === -1) throw new Error(`หา function ${name}() ใน ui.js ไม่เจอ`);

  // นับวงเล็บปีกกาเพื่อหาจุดจบของฟังก์ชัน — เชื่อถือได้กว่าการหา "\n}"
  // เพราะในตัวฟังก์ชันมี object literal ซ้อนอยู่หลายชั้น
  let depth = 0, i = source.indexOf("{", start);
  const from = i;
  for (; i < source.length; i++) {
    if (source[i] === "{") depth++;
    else if (source[i] === "}" && --depth === 0) break;
  }
  return source.slice(start, i + 1);
}

/** ดึงตัวแปรที่ประกาศเป็นลูกศรบรรทัดเดียว เช่น `const shortTime = (t) => ...` */
function grabConst(source, name) {
  const m = source.match(new RegExp(`^const ${name} = .*$`, "m"));
  if (!m) throw new Error(`หา const ${name} ไม่เจอ`);
  return m[0];
}

const sandbox = {};
vm.createContext(sandbox);
vm.runInContext(
  [
    // shortTime อยู่ใน api.js ไม่ใช่ ui.js — shopStatus เรียกใช้ตัวนี้
    grabConst(fs.readFileSync(API, "utf8"), "shortTime"),
    grab(fs.readFileSync(UI, "utf8"), "shopStatus"),
  ].join("\n\n"),
  sandbox,
  { filename: "โค้ดจริงที่ดึงมาจาก api.js + ui.js" }
);

// ------------------------------------------------------------------
// เครื่องมือทดสอบ
// ------------------------------------------------------------------
let ok = 0, fail = 0;

/** แกล้งให้ระบบคิดว่าตอนนี้เป็นเวลา hh:mm แล้วเรียก shopStatus */
function statusAt(hh, mm, open, close) {
  const Real = sandbox.Date;
  sandbox.Date = function () {
    return { getHours: () => hh, getMinutes: () => mm };
  };
  try {
    return sandbox.shopStatus({ open_time: open, close_time: close }).text;
  } finally {
    sandbox.Date = Real;
  }
}

function check(label, got, want) {
  if (got === want) {
    ok++;
    console.log(`  ✅ ${label}`);
  } else {
    fail++;
    console.log(`  ❌ ${label}\n       ได้ "${got}"\n       ควรเป็น "${want}"`);
  }
}

// ------------------------------------------------------------------
// 1) ร้านเปิด-ปิดในวันเดียวกัน — กรณีปกติที่เคยถูกอยู่แล้ว
// ------------------------------------------------------------------
console.log("\n1) ร้านปกติ เปิด 10:00 ปิด 20:00");
const NORMAL = ["10:00:00", "20:00:00"];
check("08:00 ยังไม่เปิด บอกเวลาเปิด", statusAt(8, 0, ...NORMAL), "เปิด 10:00 น.");
check("09:30 ใกล้เปิด นับถอยหลังเป็นนาที", statusAt(9, 30, ...NORMAL), "เปิดในอีก 30 นาที");
// เส้นแบ่ง "ใกล้เปิด/ใกล้ปิด" คือเหลือ <= 60 นาที — ตรงเส้นพอดีต้องนับเป็นใกล้แล้ว
check("09:00 เหลือ 60 นาทีพอดี ถือว่าใกล้เปิดแล้ว",
      statusAt(9, 0, ...NORMAL), "เปิดในอีก 60 นาที");
check("15:00 เปิดอยู่", statusAt(15, 0, ...NORMAL), "เปิดอยู่ตอนนี้");
check("19:30 ใกล้ปิด", statusAt(19, 30, ...NORMAL), "ใกล้ปิด · อีก 30 นาที");
check("21:00 ปิดแล้ว", statusAt(21, 0, ...NORMAL), "ปิดแล้ววันนี้");
check("เที่ยงคืนตรง ยังถือว่าปิด", statusAt(0, 0, ...NORMAL), "เปิด 10:00 น.");

// ------------------------------------------------------------------
// 2) ร้านเปิด 24 ชั่วโมง — บั๊กตัวที่เจอบนเว็บจริง
//
// เซิร์ฟเวอร์ถือว่า open == close คือเปิดตลอด
// ของเดิมเทียบ cur >= close (0 >= 0 เป็นจริงเสมอ) จึงขึ้น "ปิดแล้ววันนี้" ตลอดเวลา
// ------------------------------------------------------------------
console.log("\n2) สนามเปิด 24 ชั่วโมง (00:00–00:00) ← บั๊กที่เจอบนเว็บจริง");
const ALLDAY = ["00:00:00", "00:00:00"];
for (const h of [0, 6, 12, 18, 23]) {
  check(`${String(h).padStart(2, "0")}:00 ต้องบอกว่าเปิดตลอด`,
        statusAt(h, 0, ...ALLDAY), "เปิด 24 ชั่วโมง");
}
// เปิดตลอดในรูปแบบอื่นก็ต้องได้ผลเดียวกัน ไม่ใช่เฉพาะเที่ยงคืน
check("ร้าน 08:00–08:00 ก็คือเปิดตลอดเหมือนกัน",
      statusAt(3, 0, "08:00:00", "08:00:00"), "เปิด 24 ชั่วโมง");

// ------------------------------------------------------------------
// 3) ร้านที่ปิดหลังเที่ยงคืน — บั๊กตัวที่สอง
//
// คาราโอเกะเปิด 14:00 ปิด 02:00 ของอีกวัน
// ของเดิมตอนตีหนึ่งจะเข้าเงื่อนไข cur < open แล้วบอกว่า "เปิด 14:00 น."
// ทั้งที่ร้านเปิดอยู่จริง ๆ ในขณะนั้น
// ------------------------------------------------------------------
console.log("\n3) คาราโอเกะ เปิด 14:00 ปิด 02:00 ← บั๊กที่เจอบนเว็บจริง");
const LATE = ["14:00:00", "02:00:00"];
check("01:00 เปิดอยู่จริง (ช่วงหลังเที่ยงคืน)", statusAt(1, 0, ...LATE), "ใกล้ปิด · อีก 60 นาที");
check("00:30 ยังเปิดอยู่ เหลือ 90 นาที ยังไม่นับว่าใกล้ปิด",
      statusAt(0, 30, ...LATE), "เปิดอยู่ตอนนี้");
check("03:00 ปิดแล้ว แต่จะเปิดอีกบ่ายนี้", statusAt(3, 0, ...LATE), "เปิด 14:00 น.");
check("10:00 ยังไม่ถึงเวลาเปิด", statusAt(10, 0, ...LATE), "เปิด 14:00 น.");
check("13:30 ใกล้เปิด", statusAt(13, 30, ...LATE), "เปิดในอีก 30 นาที");
check("15:00 เปิดอยู่", statusAt(15, 0, ...LATE), "เปิดอยู่ตอนนี้");
check("23:00 ยังเปิดอยู่ ไม่ใช่ปิดแล้ว", statusAt(23, 0, ...LATE), "เปิดอยู่ตอนนี้");
// ร้านข้ามเที่ยงคืนต้องไม่ขึ้นคำว่า "ปิดแล้ววันนี้" เลย
// เพราะมันจะกลับมาเปิดอีกในวันปฏิทินเดียวกัน
let saidClosedToday = false;
for (let h = 0; h < 24; h++) {
  if (statusAt(h, 0, ...LATE) === "ปิดแล้ววันนี้") saidClosedToday = true;
}
check("ร้านข้ามเที่ยงคืนต้องไม่ขึ้น 'ปิดแล้ววันนี้' ในชั่วโมงใดเลย",
      saidClosedToday, false);

// ------------------------------------------------------------------
// 4) กติกาต้องตรงกับฝั่งเซิร์ฟเวอร์
//
// เทียบกับ _windows_for() ใน app/routers/bookings.py โดยตรง
// ถ้าวันหนึ่งมีคนไปแก้ฝั่งใดฝั่งหนึ่ง เทสต์ข้อนี้จะแดงทันที
// ------------------------------------------------------------------
console.log("\n4) ต้องบอกว่า 'เปิดอยู่' เฉพาะชั่วโมงที่เซิร์ฟเวอร์ยอมให้จองเท่านั้น");
const OPEN_WORDS = ["เปิดอยู่ตอนนี้", "ใกล้ปิด", "เปิด 24 ชั่วโมง"];
const isOpen = (t) => OPEN_WORDS.some((w) => t.startsWith(w));

/** ลอกตรรกะของ _windows_for() มาเทียบ — เปิด==ปิด คือ 24 ชม. · เปิด>ปิด คือข้ามคืน */
function serverSaysOpen(cur, open, close) {
  if (open === close) return true;
  return open < close ? (cur >= open && cur < close) : (cur >= open || cur < close);
}

const CASES = [
  ["ร้านปกติ", 600, 1200, NORMAL],
  ["เปิด 24 ชม.", 0, 0, ALLDAY],
  ["ข้ามเที่ยงคืน", 840, 120, LATE],
];
let mismatch = 0;
for (const [name, o, c, times] of CASES) {
  for (let m = 0; m < 1440; m += 10) {
    const web = isOpen(statusAt(Math.floor(m / 60), m % 60, ...times));
    if (web !== serverSaysOpen(m, o, c)) {
      if (mismatch < 3) {
        console.log(`       ต่างกันที่ ${name} เวลา ${String(Math.floor(m / 60)).padStart(2, "0")}:${String(m % 60).padStart(2, "0")}`);
      }
      mismatch++;
    }
  }
}
check("ทั้ง 3 แบบร้าน x 144 ช่วงเวลา ต้องตรงกับเซิร์ฟเวอร์ทุกจุด", mismatch, 0);

// ------------------------------------------------------------------
console.log("\n" + "=".repeat(60));
console.log(`สรุป: ผ่าน ${ok} · ไม่ผ่าน ${fail}`);
console.log("=".repeat(60));
process.exit(fail ? 1 : 0);
